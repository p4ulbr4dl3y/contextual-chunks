"""Export the labelled SFT dataset to `hf_export/` (parquet + dataset card).

Splits are grouped by `doc_hash` so identical/duplicate documents never land on
both sides of the train/val boundary.

    .venv/bin/python -m contextual_chunks.dataset.export_hf
    .venv/bin/python -m contextual_chunks.dataset.export_hf --repo-id user/name --push     # requires HF_TOKEN
"""

import os
import json
import argparse
import collections

from contextual_chunks import paths
from datasets import Dataset, DatasetDict

CARD = """---
task_categories:
- text-generation
language:
- ru
tags:
- contextual-retrieval
- rag
- question-answering
size_categories:
- 1K<n<10K
---

# Russian contextual-retrieval contexts

Chunks from Russian public-procurement documents with a 1-2 sentence context
that situates the chunk inside its document (Anthropic-style contextual
retrieval). Generated by `cline-pass/deepseek-v4.1-flash` with thinking
disabled.

* student: `Qwen/Qwen3-0.6B`
* rows: {rows} (train {train} / val {val}, split by `window_hash` -- identical
  prompts, e.g. from near-duplicate documents, never straddle the boundary)
* context length: median {med} chars, max {mx} chars
* dataset card generated by `export_hf.py`
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="inp", default=paths.SFT)
    ap.add_argument("--out", dest="out", default=paths.HF_EXPORT)
    ap.add_argument("--repo-id")
    ap.add_argument("--push", action="store_true")
    ap.add_argument("--val-frac", type=float, default=0.15)
    ap.add_argument("--seed", type=int, default=3407)
    a = ap.parse_args()

    rows = [json.loads(l) for l in open(a.inp, encoding="utf-8")]
    if not rows:
        raise SystemExit(f"{a.inp} is empty")

    def key(r):
        return r.get("window_hash") or r.get("doc_hash") or r["id"].rsplit("_chunk_", 1)[0]

    import random

    groups = sorted({key(r) for r in rows})
    random.Random(a.seed).shuffle(groups)
    n_val = 0 if len(groups) < 2 else max(1, int(len(groups) * a.val_frac))
    val_groups = set(groups[:n_val])

    train = [r for r in rows if key(r) not in val_groups]
    val = [r for r in rows if key(r) in val_groups]
    ds = DatasetDict({
        "train": Dataset.from_list(train),
        "validation": Dataset.from_list(val),
    })
    os.makedirs(a.out, exist_ok=True)
    ds.save_to_disk(a.out)
    lens = [len(r["messages"][-1]["content"]) for r in rows]
    with open(os.path.join(a.out, "README.md"), "w", encoding="utf-8") as f:
        f.write(CARD.format(rows=len(rows), train=len(train), val=len(val),
                            med=sorted(lens)[len(lens) // 2], mx=max(lens)))

    print(f"rows:       {len(rows)}  (train {len(train)} / val {len(val)})")
    print(f"doc groups: {len(groups)}  (val groups {n_val})")
    print(f"output:     {a.out}")

    if a.push:
        if not a.repo_id:
            raise SystemExit("--push requires --repo-id")
        ds.push_to_hub(a.repo_id)


if __name__ == "__main__":
    main()
