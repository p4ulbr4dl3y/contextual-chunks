"""Corpus: chunks + distilled context -> text for indexing.

Source: `data/interim/labeled_dataset_metadata.jsonl` (3134 chunks, 82 docs):
it already holds both the raw chunk and the teacher's `generated_context`, so arms A/B
are built from one file and differ only in how the text is concatenated.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from contextual_chunks import paths
from contextual_chunks.retrieval.config import CHUNKS_FILE

SEP = "\n\n"
STUDENT_CONTEXT = Path(paths.STUDENT_CONTEXT)


@dataclass(frozen=True)
class Chunk:
    idx: int                # position in the corpus (= Qdrant point id)
    cid: str                # original dataset id
    doc_id: str
    chunk: str
    context: str
    is_table: bool
    chunk_tokens: int
    is_requisites: bool = False
    doc_chunk_index: int = 0
    window_index: int = 0
    chunk_index: int = 0

    def text(self, mode: str = "chunk") -> str:
        """The text that the embedder and BM25 actually encode."""
        if mode == "chunk":
            return self.chunk
        if mode == "context":
            return self.context or self.chunk
        if mode == "context_chunk":
            return f"{self.context}{SEP}{self.chunk}" if self.context else self.chunk
        raise ValueError(f"unknown index_text mode: {mode}")

    def to_payload(self, mode: str = "chunk") -> dict:
        return {"cid": self.cid, "doc_id": self.doc_id, "text": self.text(mode),
                "chunk": self.chunk, "is_table": self.is_table,
                "chunk_tokens": self.chunk_tokens, "idx": self.idx,
                "is_requisites": self.is_requisites,
                "doc_chunk_index": self.doc_chunk_index}


def load_student_context(path: Path | str = STUDENT_CONTEXT) -> dict[str, str]:
    """chunk id -> context generated by the student model.

    The key is `id` (unique: `doc_id`+`window`+`chunk`); `(doc_id, chunk_index)`
    is not unique because `chunk_index` is numbered within a window.
    """
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"no student context: {p} (run gen_student_context.py first)")
    out: dict[tuple[str, int], str] = {}
    for line in p.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        r = json.loads(line)
        out[r["id"]] = (r.get("context") or "").strip()
    return out


def load(path: Path | str = CHUNKS_FILE, limit: int | None = None,
         offset: int = 0, only_docs: list[str] | None = None,
         context_source: str = "teacher") -> list[Chunk]:
    """Reads the corpus in file order (determinism is needed for point ids)."""
    student = load_student_context() if context_source == "student" else {}
    out: list[Chunk] = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            if only_docs is not None and r["doc_id"] not in only_docs:
                continue
            ctx = r.get("generated_context", "") or ""
            if context_source == "student":
                ctx = student.get(r["id"], "")
            out.append(Chunk(idx=len(out), cid=r["id"], doc_id=r["doc_id"],
                             chunk=r["chunk"], context=ctx,
                             is_table=bool(r.get("is_table")),
                             chunk_tokens=int(r.get("chunk_tokens") or 0),
                             is_requisites=bool(r.get("is_requisites")),
                             doc_chunk_index=int(r.get("doc_chunk_index") or 0),
                             window_index=int(r.get("window_index") or 0),
                             chunk_index=int(r.get("chunk_index") or 0)))
    if offset:
        out = out[offset:]
    if limit:
        out = out[:limit]
    return [Chunk(idx=i, cid=c.cid, doc_id=c.doc_id, chunk=c.chunk, context=c.context,
                  is_table=c.is_table, chunk_tokens=c.chunk_tokens,
                  is_requisites=c.is_requisites, doc_chunk_index=c.doc_chunk_index,
                  window_index=c.window_index, chunk_index=c.chunk_index)
            for i, c in enumerate(out)]


def stats(chunks: list[Chunk]) -> dict:
    n_ctx = sum(1 for c in chunks if c.context)
    return {"chunks": len(chunks), "docs": len({c.doc_id for c in chunks}),
            "with_context": n_ctx, "tables": sum(1 for c in chunks if c.is_table),
            "requisites": sum(1 for c in chunks if c.is_requisites),
            "avg_chunk_tokens": round(sum(c.chunk_tokens for c in chunks) / max(1, len(chunks)), 1),
            "avg_context_chars": round(sum(len(c.context) for c in chunks) / max(1, len(chunks)), 1)}
