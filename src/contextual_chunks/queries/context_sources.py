"""Comparison of teacher and student contexts by retrieval metrics (for the paper).

Reads the JSON reports of `eval_queries.py` and builds a markdown table plus deltas for
pairs "same arm, but the context was generated by the student model" (F->G dense-only,
B->H RRF).

    .venv/bin/python -m contextual_chunks.queries.context_sources
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from contextual_chunks import paths

RESULTS = Path(paths.RESULTS)

METRICS = [("recall@1", "R@1"), ("recall@5", "R@5"), ("recall@10", "R@10"),
           ("recall@50", "R@50"), ("mrr@10", "MRR@10"), ("ndcg@10", "nDCG@10"),
           ("doc_recall@10", "docR@10"), ("miss@50", "miss@50")]
PAIRS = [("F", "G", "dense-only"), ("B", "H", "RRF")]


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def fmt(v: float) -> str:
    return f"{v:.3f}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--teacher", type=Path, default=RESULTS / "retrieval_eval_full.json")
    ap.add_argument("--student", type=Path, default=RESULTS / "retrieval_eval_student.json")
    ap.add_argument("--out", type=Path, default=RESULTS / "retrieval_student_vs_teacher.md")
    args = ap.parse_args()

    t, s = load(args.teacher), load(args.student)
    lines = ["# Retrieval: teacher context vs student model", ""]
    lines += [f"- corpus: {t['corpus']} chunks, queries: {t['queries']} "
              f"(teacher), {s['queries']} (student)",
              f"- backend: {t['backend']}, tag: {t['tag']}", ""]

    lines += ["## Metrics by arm", "",
              "| arm | " + " | ".join(lbl for _, lbl in METRICS) + " | p50 ms |",
              "|---|" + "---|" * (len(METRICS) + 1)]
    for src, label in ((t, "teacher"), (s, "student")):
        for arm, rep in src["arms"].items():
            m = rep["metrics"]
            lines.append(f"| {rep['name']} ({label}) | "
                         + " | ".join(fmt(m[k]) for k, _ in METRICS)
                         + f" | {rep['latency']['total_p50_ms']:.0f} |")
    lines.append("")

    lines += ["## Delta: student − teacher (same arm)", "",
              "| arm | " + " | ".join(lbl for _, lbl in METRICS) + " |",
              "|---|" + "---|" * len(METRICS)]
    for ta, sa, kind in PAIRS:
        if ta not in t["arms"] or sa not in s["arms"]:
            continue
        mt, ms = t["arms"][ta]["metrics"], s["arms"][sa]["metrics"]
        cells = []
        for k, _ in METRICS:
            d = ms[k] - mt[k]
            cells.append(f"{d:+.3f}")
        lines.append(f"| {kind}: {ta}→{sa} | " + " | ".join(cells) + " |")
    lines.append("")

    lines += ["## Conclusions", "",
              "- Student-model context (0.6B, distillation) vs teacher context:",
              "  the quality cost of moving context generation to an edge device.",
              "- Indexes: G = student-ctx/dense-only (pairs with F), H = student-ctx/RRF (pairs with B).",
              "- Student context was generated by MLX bf16 on M2 with KV-cache reuse",
              "  (shared `<document>` of one window), see `src/contextual_chunks/latency/gen_student_context.py`.", ""]
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"-> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
